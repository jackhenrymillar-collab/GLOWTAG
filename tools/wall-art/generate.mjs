// Turns the drawings in art.mjs into Source/UI/DeviceWallArtData.inc.
// Run from the repository root:  node tools/wall-art/generate.mjs
import { writeFileSync } from 'node:fs';
import { ART, ART2, ART3, deco3 } from './art.mjs';

// Same order as the device table in Source/UI/DeviceWallModel.cpp
const ids = ['synth','sampler','drums','filter','delay','reverb','eq','comp','drive','lfo',
             'clock','steps','euclid','turing','burst','chance','quantise','mutate','circadian','tide','out',
             'gas','crate','strings','ghost','crowd','xfmr'];

const mul = (a, b) => [a[0]*b[0]+a[2]*b[1], a[1]*b[0]+a[3]*b[1], a[0]*b[2]+a[2]*b[3], a[1]*b[2]+a[3]*b[3],
                       a[0]*b[4]+a[2]*b[5]+a[4], a[1]*b[4]+a[3]*b[5]+a[5]];
const ident = [1, 0, 0, 1, 0, 0];

function parseTransform (text) {
  let m = ident;
  for (const [, fn, args] of text.matchAll(/(\w+)\(([^)]*)\)/g)) {
    const v = args.trim().split(/[\s,]+/).map(Number);
    if (fn === 'translate') m = mul(m, [1, 0, 0, 1, v[0], v[1] ?? 0]);
    else if (fn === 'scale') m = mul(m, [v[0], 0, 0, v[1] ?? v[0], 0, 0]);
    else if (fn === 'rotate') {
      const a = v[0] * Math.PI / 180, c = Math.cos(a), s = Math.sin(a), cx = v[1] ?? 0, cy = v[2] ?? 0;
      m = mul(m, mul([1, 0, 0, 1, cx, cy], mul([c, s, -s, c, 0, 0], [1, 0, 0, 1, -cx, -cy])));
    } else throw new Error('transform ' + fn);
  }
  return m;
}

const attr = (tag, name) => { const m = tag.match(new RegExp(`(?:^|\\s)${name}="([^"]*)"`)); return m ? m[1] : null; };

function parse (markup) {
  const out = [], stack = [{ m: ident, spin: false }];
  for (const [tag] of markup.matchAll(/<[^>]+>/g)) {
    const top = stack[stack.length - 1];
    if (tag.startsWith('</g')) { stack.pop(); continue; }
    if (tag.startsWith('<g')) {
      const t = attr(tag, 'transform');
      stack.push({ m: t ? mul(top.m, parseTransform(t)) : top.m, spin: top.spin || attr(tag, 'class') === 'spin' });
      continue;
    }
    const shape = tag.startsWith('<path') ? 'P' : tag.startsWith('<circle') ? 'C' : tag.startsWith('<rect') ? 'R' : null;
    if (! shape) throw new Error('tag ' + tag);
    const el = { shape, cls: attr(tag, 'class'), v: [0, 0, 0, 0, 0], d: '', dash: [0, 0], m: top.m, flags: 0 };
    if (shape === 'P') { el.d = attr(tag, 'd'); if (/z\s*$/i.test(el.d)) el.flags |= 1; }
    if (shape === 'C') { el.v = [attr(tag, 'cx'), attr(tag, 'cy'), attr(tag, 'r'), 0, 0].map(Number); el.flags |= 1; }
    if (shape === 'R') { el.v = ['x', 'y', 'width', 'height', 'rx'].map(n => Number(attr(tag, n))); el.flags |= 1; }
    const dash = attr(tag, 'stroke-dasharray');
    if (dash) el.dash = dash.trim().split(/[\s,]+/).map(Number);
    if (top.spin) el.flags |= 2;
    if (attr(tag, 'style')) el.flags |= 4;            // the compressor needle, which follows the beat
    if (el.m !== ident) el.flags |= 8;
    out.push(el);
  }
  return out;
}

const f = n => { const s = String(+n.toFixed(4)); return (s.includes('.') || s.includes('e') ? s : s + '.0') + 'f'; };
let code = '// Generated by tools/wall-art/generate.mjs from tools/wall-art/art.mjs. Do not edit by hand.\n\n';
const table = [];
ids.forEach((id, i) => {
  const styles = [ART[id](), ART2[id](), deco3(i, ART3[id]())].map(parse);
  styles.forEach((els, s) => {
    code += `static const WallArt::Element ${id}_${s + 1}[] = {\n`;
    for (const e of els)
      code += `    { '${e.shape}', '${e.cls}', ${e.flags}, { ${e.dash.map(f).join(', ')} }, { ${e.v.map(f).join(', ')} }, "${e.d}", { ${e.m.map(f).join(', ')} } },\n`;
    code += '};\n';
  });
  table.push(`    { { ${[1, 2, 3].map(s => `{ ${id}_${s}, ${styles[s - 1].length} }`).join(', ')} } },`);
});
code += `\nstatic const WallArt::Device wallArtTable[] = {\n${table.join('\n')}\n};\n`;
writeFileSync('Source/UI/DeviceWallArtData.inc', code);
console.log(`wrote ${ids.length} devices x 3 styles`);
